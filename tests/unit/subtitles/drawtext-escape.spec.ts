import { describe, expect, it } from "vitest"
import { escapeDrawtext } from "../../../server/utils/render"

/**
 * Проверено живым ffmpeg в контейнере: внутри `text='...'` запятая проходит как
 * литерал, а двоеточие обрывает строку — парсер начинает читать остаток фильтра
 * как имя опции и весь монтаж падает.
 */
describe("экранирование текста для drawtext", () => {
  it("экранирует двоеточие, которое обрывает фильтр", () => {
    expect(escapeDrawtext("Смотрите на этикетку: две ложки"))
      .toBe("Смотрите на этикетку\\: две ложки")
  })

  it("оставляет запятую как есть — её ffmpeg принимает", () => {
    expect(escapeDrawtext("салаты, йогурты, соки"))
      .toBe("салаты, йогурты, соки")
  })

  it("заменяет одинарную кавычку, чтобы не закрыть строку", () => {
    expect(escapeDrawtext("это 'полезно'")).toBe("это ’полезно’")
  })

  it("удваивает процент — ffmpeg разворачивает его как подстановку", () => {
    expect(escapeDrawtext("0% жира")).toBe("0%% жира")
  })

  it("переживает реплику со всеми опасными символами разом", () => {
    const result = escapeDrawtext("Йогурт 0%: 'лёгкий', но сахара — на треть больше")

    expect(result).not.toMatch(/(^|[^\\]):/)
    expect(result).not.toContain("'")
    expect(result).toContain("%%")
  })
})
