/**
 * Где вообще можно резать таймлайн, не разрезав слово.
 *
 * Один источник истины для трёх мест, которые раньше считали межсловные
 * интервалы каждое по-своему: сетка кадров (`grid.ts`), ремонт границ
 * (`repair.ts`) и дробление длинной реплики (`split-line.ts`). Расхождение
 * между «где ищем рез» и «что считаем нарушением» в этом модуле уже однажды
 * стоило ролика (см. ниже), поэтому определение «стыка» живёт в одном файле, а
 * не в трёх копиях.
 *
 * Боевой дефект 28.08.2026 (ролик 34). Все три места собирали кандидатов
 * условием `next > end` — то есть считали кандидатом ТОЛЬКО интервал
 * положительной ширины. Модель транскрипции `vaibhavs10/incredibly-fast-whisper`
 * (перешли 27.08, коммит `b8dfc22`) отдаёт слова ВСТЫК: `endSec` слова ровно
 * равен `startSec` следующего. На такой транскрипции список кандидатов пуст
 * целиком, код режет по наивной точке `cursor + shotChangeSec`, она приходится
 * на середину слова, и шаг `edit_plan` падает с `word_split` по двум десяткам
 * кадров — уже после двух платных запросов к модели.
 *
 * Соображение, на котором держится фикс: граница РОВНО НА СТЫКЕ двух слов
 * никакого слова не разрезает. Она законна — просто её ширина нулевая, и
 * поставить точку «с запасом от краёв» внутри неё нельзя, там нет места.
 * Отсюда два тира, а не один список:
 *
 *  - {@link WordCutCandidates.pauses} — настоящие паузы. Рез в паузе выглядит
 *    намеренным (§5.3 п.1), это по-прежнему первый выбор.
 *  - {@link WordCutCandidates.junctions} — стыки. Рез на стыке резче, чем в
 *    паузе, но он законен и это единственная альтернатива резу по живому
 *    слову. Берётся, только когда ни одна пауза не подошла.
 *
 * Почему стык остаётся безопасным ПОСЛЕ притяжки к кадру (`snapSecToFrame`):
 * притяжка сдвигает точку не больше чем на половину кадра, а допуск «рвёт ли
 * граница слово» (`wordEdgeToleranceSec` в `validate.ts`) — половина кадра
 * ПЛЮС 3 мс. То есть снятая к кадру точка стыка гарантированно остаётся в
 * допуске у края слова на любом fps, и валидация её нарушением не считает.
 */

/** Интервал между словами, внутри которого можно резать. У стыка `startSec === endSec`. */
export interface WordGap {
  startSec: number
  endSec: number
}

export interface WordCutCandidates {
  /** Настоящие паузы: между словами есть тишина. Приоритетный тир. */
  pauses: WordGap[]
  /** Стыки слов: тишины нет, но и слова такой рез не рвёт. Запасной тир. */
  junctions: WordGap[]
}

/**
 * Ниже этой ширины интервал считается стыком, а не паузой.
 *
 * Микросекунда — не эстетика, а защита от шума плавающей точки: тайминги
 * приходят из внешнего API, и «пауза» шириной 1e-9 с — это тот же стык,
 * записанный чуть иначе. Держать её в приоритетном тире значило бы отдавать
 * приоритет паузы тому, что паузой не является ни на слух, ни на монтаже.
 */
const JUNCTION_EPS_SEC = 1e-6

/**
 * Кандидаты на рез между соседними словами, разложенные по приоритету.
 *
 * Слова, которые НАКЛАДЫВАЮТСЯ (`next < end` заметно) кандидата не дают вовсе:
 * весь интервал между ними лежит ВНУТРИ обоих слов сразу, и безопасной точки
 * там нет по определению. Это сохраняет прежнее поведение — прежнее условие
 * `next > end` такие пары тоже отбрасывало.
 *
 * Нечисловые границы (NaN/Infinity) отсеиваются сами: любое сравнение с NaN
 * ложно, поэтому пара не попадает ни в один тир.
 */
export function collectWordCutCandidates(
  words: readonly { startSec: number, endSec: number }[],
): WordCutCandidates {
  const sorted = [...words].sort((a, b) => a.startSec - b.startSec)
  const pauses: WordGap[] = []
  const junctions: WordGap[] = []

  for (let index = 0; index + 1 < sorted.length; index += 1) {
    const end = sorted[index]!.endSec
    const next = sorted[index + 1]!.startSec
    const width = next - end

    if (width > JUNCTION_EPS_SEC) {
      pauses.push({ startSec: end, endSec: next })
      continue
    }
    if (width >= -JUNCTION_EPS_SEC) {
      // Стык: обе границы сходятся в одной точке. Берём середину, чтобы
      // микроскопический перехлёст/зазор не сдвинул точку в сторону одного из
      // соседей.
      const at = (end + next) / 2
      junctions.push({ startSec: at, endSec: at })
    }
  }

  return { pauses, junctions }
}
