/**
 * Порог, после которого `ingestStatus: "running"` у записи ведущего считается
 * зависшим, а не активной работой.
 *
 * Процесс, убитый на середине (kill -9, деплой, OOM на 4K-записи), не успевает
 * снять статус — без порога такая запись заперта навсегда сразу в двух местах:
 * `reingestRecording` (server/utils/presenter/recording-store.ts) всегда
 * бросает `RecordingIngestRunningError`, а автоочистка
 * (server/utils/presenter/recording-retention.ts) считает её вечно живой и
 * никогда не тронет ни файл, ни строку (Minor 4 финального ревью). Значение —
 * с большим запасом над `CUT_TIMEOUT_MS` (5 мин на сегмент) и
 * `NORMALIZE_TIMEOUT_MS` (60 мин на всю запись) из ffmpeg-adapter.ts: у
 * длинной записи может быть много сегментов, и последовательная обработка
 * десятков из них — обычная работа, а не зависание. 2 часа — заведомо больше
 * любого штатного прогона и заведомо меньше «оператор ждёт сутки, пока само
 * пройдёт».
 *
 * Вынесен в отдельный файл БЕЗ побочных импортов: recording-retention.ts
 * (чистое правило хранения, DB-free unit-тест vitest.pure.config.ts) не может
 * статически импортировать этот порог из recording-store.ts — тот статически
 * тянет Prisma-клиент (`import { prisma } from "../prisma"`), а его модуль
 * верхнего уровня открывает соединение с БД уже на `import`. Общий файл без
 * импортов даёт обоим потребителям одно число без этой проблемы.
 */
export const STALE_RUNNING_THRESHOLD_MS = 2 * 60 * 60_000
