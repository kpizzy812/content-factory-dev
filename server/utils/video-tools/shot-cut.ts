/**
 * Вырезка подотрезка готового видео под кадр монтажа.
 *
 * Зачем отдельно: в проекте вырезки `[a, b]` для видео не было вовсе.
 * `buildClipTrimArgs` (`render.ts`) режет только ОТ НУЛЯ, а единственная
 * произвольная вырезка — `buildPresenterCutArgs` в `presenter/ffmpeg-adapter.ts`
 * — принудительно масштабирует в 1080x1920 и заточена под запись ведущего.
 *
 * Чистая функция: собирает аргументы, процесс не запускает (по образцу
 * `buildStillClipArgs` в `./still-clip.ts`). Модуль НЕ импортирует
 * `./ffmpeg.ts`: тот на уровне модуля зовёт `setFfmpegPath`, и его появление в
 * графе ломает инвариант lip-sync.
 *
 * Семантика `-t`: `anullsrc` (второй `-i`) — бесконечный генератор, но `-t`
 * здесь стоит ПОСЛЕ обоих `-i` и перед выходным файлом, поэтому ffmpeg
 * трактует его как ВЫХОДНУЮ опцию — она обрезает результат ровно по
 * `durationSec` независимо от длины входов. `-shortest` в этой связке
 * избыточен (то же самое уже делает `-t`), но оставлен для единообразия с
 * `still-clip.ts`, где `-loop 1` на картинке тоже бесконечен и работает по
 * той же связке `-t` + `-shortest`.
 *
 * Звук: клип кадра ВСЕГДА получает синтетическую немую дорожку, родной звук
 * источника не переносится НИКОГДА. Это не временное упрощение, а следствие
 * §6.4 спеки «монтаж от звука»: единственная звуковая дорожка ролика — уже
 * сведённый непрерывный трек (voiceover/музыка), и родной звук клипа ведущего
 * или библиотечного фона поверх него дал бы дублирующую речь с эхом —
 * громкость клипа кадра держится в нуле независимо от того, есть ли у
 * источника собственное аудио.
 *
 * Фикс-раунд 1 (task-2-review.md, Important #2): поля `audioPresent` в
 * интерфейсе больше нет — было эмпирически показано (реальный ffmpeg 8.1) на
 * ДВУХ независимых уровнях, что попытка выбирать между «есть/нет своего
 * звука» ненадёжна в принципе:
 * 1) Если вызывающий ошибается и говорит `audioPresent: true` про реально
 *    немой источник, ffmpeg не падает — он молча пишет файл БЕЗ аудиопотока
 *    вовсе (1 stream вместо 2), и разнородные потоки всплывают только в
 *    concat, а не здесь.
 * 2) Даже при БЕЗУСЛОВНОМ добавлении `anullsrc` вторым входом, БЕЗ явного
 *    `-map` автовыбор ffmpeg решает, какой аудиопоток класть в выход, по
 *    числу каналов; если у источника реально СТЕРЕО-звук (то же число
 *    каналов, что и у `anullsrc`), при равенстве побеждает поток с МЕНЬШИМ
 *    индексом — то есть родной звук источника (замерено: `mean_volume`
 *    -21.1 dB — слышимый тон), а НЕ синтетическая тишина (-91 dB — цифровой
 *    шум квантования). Источник звука в выходе решал не `-t`/`-af`, а
 *    случайное совпадение числа каналов.
 * Поэтому вход только один: `anullsrc` добавляется БЕЗУСЛОВНО, а видео- и
 * аудиопоток маппятся ЯВНО (`-map 0:v:0 -map 1:a:0`) — автовыбор ffmpeg из
 * уравнения исключён совсем, и никакая ложь вызывающего про исходный звук
 * больше не имеет пути повлиять на результат.
 */

import { TIMELINE_FPS } from "~~/shared/types/video-runtime"

export interface ShotSubClipRequest {
  sourcePath: string
  startSec: number
  durationSec: number
  outputPath: string
}

/** Кадр короче этого не существует: ffmpeg отдаёт пустой файл. */
const MIN_SUB_CLIP_SEC = 1 / TIMELINE_FPS

function finiteOrZero(value: number): number {
  return Number.isFinite(value) ? value : 0
}

export function buildShotSubClipArgs(request: ShotSubClipRequest): string[] {
  const startSec = Math.max(0, finiteOrZero(request.startSec))
  const durationSec = Math.max(MIN_SUB_CLIP_SEC, finiteOrZero(request.durationSec))

  return [
    "-y",
    // -ss ПЕРЕД -i: быстрый поиск по контейнеру. При обратном порядке ffmpeg
    // декодирует весь клип до точки реза, и на сорока кадрах это минуты.
    "-ss", startSec.toFixed(3),
    "-i", request.sourcePath,
    // Синтетическая немая дорожка — БЕЗУСЛОВНО, для любого источника (§6.4).
    "-f", "lavfi", "-i", "anullsrc=channel_layout=stereo:sample_rate=44100",
    // Явный маппинг ОБЯЗАТЕЛЕН: без него автовыбор ffmpeg при стерео-звуке у
    // источника берёт РОДНОЙ звук вместо anullsrc (см. докстринг выше).
    "-map", "0:v:0",
    "-map", "1:a:0",
    "-t", durationSec.toFixed(3),
    // Пересчёт PTS обязателен: без него у вырезки остаётся исходный штамп
    // времени, и concat кладёт кадр не туда.
    "-vf", `setpts=PTS-STARTPTS,fps=${TIMELINE_FPS},format=yuv420p`,
    "-af", "asetpts=PTS-STARTPTS",
    "-c:v", "libx264",
    "-preset", "veryfast",
    "-crf", "22",
    "-profile:v", "high",
    "-level", "4.1",
    "-pix_fmt", "yuv420p",
    "-c:a", "aac",
    "-b:a", "128k",
    "-ar", "44100",
    "-ac", "2",
    "-shortest",
    "-movflags", "+faststart",
    request.outputPath,
  ]
}
