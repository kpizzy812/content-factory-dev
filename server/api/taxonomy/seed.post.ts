export default defineEventHandler(async (event) => {
  await requireScopedAccess(event, {
    permissions: ['canAdmin'],
    moduleSlug: 'pipeline',
  })

  let created = 0
  let skipped = 0

  for (const item of SEED_DATA) {
    const existing = await prisma.taxonomyItem.findUnique({
      where: { type_slug: { type: item.type, slug: item.slug } },
    })

    if (existing) {
      skipped++
      continue
    }

    await prisma.taxonomyItem.create({
      data: { ...item, isSystem: true },
    })
    created++
  }

  return {
    data: { created, skipped, total: SEED_DATA.length },
  }
})
