-- Сценарий, личный для ролика: правки реплик хранятся на РОЛИКЕ, а не в варианте.
--
-- Локальная замена фразы обязана писать новый текст в сценарий: трек озвучки —
-- производная сценария, и полная перегенерация собирает его заново из storyPlan.
-- Писала она в ScenarioVariant.storyPlan, а вариант ОБЩИЙ: Video.variantId
-- уникальности не даёт, один вариант кормит сколько угодно роликов, а конвейер
-- и вовсе выбирает вариант через Scenario.selectedVariantId — на ролик не
-- смотрит вообще. Правка фразы на одном ролике переписывала сценарий соседнему,
-- уже снятому или снимающемуся, и тот при первой же перегенерации синтезировал
-- чужой текст и платил за него: сначала TTS, следом lip-sync всех сцен.
--
-- Формат: { "v": 1, "lines": [{ "sceneOrder": 2, "target": "spoken", "text": "…", "at": "…" }] }
-- Разбор и наложение — server/utils/voiceover/script-overrides.ts.
--
-- Хранится ПАТЧ (список поправленных реплик), а не копия плана: копия на каждом
-- ролике это и рост базы, и потеря наследования — законные правки общего
-- варианта (rework, регенерация блока, субтитры) перестали бы до ролика
-- доезжать.
--
-- Колонка nullable без дефолта, ровно как соседняя editOverrides: у всех
-- существующих роликов правок не было, и null означает «читаю общий сценарий
-- как есть». Миграция данных поэтому не нужна — старые ролики продолжают
-- работать без единого UPDATE.

-- AlterTable
ALTER TABLE "Video" ADD COLUMN     "scriptOverrides" JSONB;
