-- Клон голоса: чем доказывается, что за этот образец уже заплатили.
--
-- Прогон minimax/voice-cloning стоит $3, и штатный ключ идемпотентности
-- медиазадачи (server/utils/media-provider/media-identity.ts) здесь не спасает:
-- он считается по payload'у, а в payload'е стоит ПОДПИСАННАЯ ссылка на образец
-- — новая при каждом запросе, значит и ключ каждый раз новый.
--
-- Поэтому дедуп держится на самом файле: sha1 образца (первые 16 hex, как у
-- PresenterSourceClip.sha1 и CharacterReferenceImage.sha1) рядом с voiceId и
-- voiceModelId. Совпали все три — голос уже обучен, платить не за что.
-- Модель в паре обязательна: клон обучается ПОД конкретную TTS-модель, и тот
-- же voice_id в другой модели не существует.
--
-- Колонка nullable без дефолта: у существующих персонажей образца нет вовсе, и
-- пустая строка была бы неправдой — «клона не делали» и «клон сделан из файла с
-- пустым отпечатком» это разные состояния.

